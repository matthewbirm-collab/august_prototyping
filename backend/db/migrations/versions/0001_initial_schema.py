# Hourly rollup of the consensus rows written by /p3-consensus (de-vig can't run in SQL).
CONSENSUS_HOURLY = """
CREATE MATERIALIZED VIEW consensus_hourly
WITH (timescaledb.continuous, timescaledb.materialized_only = false) AS
SELECT
    time_bucket(INTERVAL '1 hour', captured_at) AS bucket,
    game_id,
    player_id,
    market_key,
    last(fair_line, captured_at) AS fair_line,
    last(fair_p_over, captured_at) AS fair_p_over,
    avg(dispersion) AS avg_dispersion,
    max(books_count) AS max_books,
    count(*) AS snapshots
FROM consensus_snapshots
GROUP BY bucket, game_id, player_id, market_key
WITH NO DATA
"""


